    private void actualizarPedido() {
        int total = 0;
        String seleccion = "Bebida:\n";
        String leches = "";

        // Revisar bebidas
        if (jRadioButton1.isSelected()) {
            seleccion += "- Café Americano\n";
            total += 40;
        } else if (jRadioButton2.isSelected()) {
            seleccion += "- Moka\n";
            total += 60;
        } else if (jRadioButton3.isSelected()) {
            seleccion += "- Café de la Casa\n";
            total += 35;
        }

        // Revisar leches/complementos
        if (jCheckBox1.isSelected()) {
            leches += "  + Leche\n";
            total += 10;
        }
        if (jCheckBox2.isSelected()) {
            leches += "  + Azucar\n";
            total += 10;
        }
        if (jCheckBox3.isSelected()) {
            leches += "  + Jarabe\n";
            total += 10;
        }

        // Mandar el texto al cuadro azul (SELECCION ACTUAL)
        if (!leches.isEmpty()) {
            jTextArea1.setText(seleccion + "\nComplementos:\n" + leches);
        } else {
            jTextArea1.setText(seleccion);
        }

        // Mandar el número al cuadro rojo (TOTAL)
        jTextArea2.setText("$ " + total);
    }
